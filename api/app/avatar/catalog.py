"""Loads shared/avatar/catalog.json, the parts library both the web app and the API draw from.

The file is generated by shared/avatar/build_catalog.py. AVATAR_CATALOG overrides the path
(the Docker image copies it next to the app).
"""

import json
import os
from functools import lru_cache
from pathlib import Path
from typing import Any

from app.config import REPO_DIR

DEFAULT_PATH = REPO_DIR / "shared" / "avatar" / "catalog.json"

Catalog = dict[str, Any]


def catalog_path() -> Path:
    return Path(os.environ.get("AVATAR_CATALOG") or DEFAULT_PATH)


@lru_cache
def load_catalog() -> Catalog:
    data: Catalog = json.loads(catalog_path().read_text(encoding="utf-8"))
    return data
